const OPEN_SLUGS = ['sintel', 'tears-of-steel', 'big-buck-bunny', 'elephants-dream'];

const GENRE_ORDER = [18, 12, 35, 16, 878, 53, 9648, 10749, 10751, 99, 14, 28, 10402];

function toTitle(seed: Seed, index: number): Title {
  return {
    id: `mock-${seed.slug}`,
    source: 'mock',
    mediaType: seed.mediaType,
    title: seed.title,
    titleAr: seed.titleAr,
    overview: seed.overview,
    overviewAr: seed.overviewAr,
    posterUrl: null,
    backdropUrl: null,
    rating: seed.rating,
    year: seed.year,
    genreIds: seed.genreIds,
    genreNames: [],
    hue: seed.hue,
    pattern: seed.pattern,
    trailerKey: seed.trailerKey ?? null,
    runtime: seed.runtime ?? null,
    seasons: seed.seasons ?? null,
    cast: seed.cast ?? fictionalCast(index + 1),
    detailsLoaded: true,
    detailsError: false,
    openCinema: Boolean(seed.openCinema),
    credit: seed.credit ?? null,
  };
}

export const MOCK_TITLES: Title[] = SEEDS.map(toTitle);

const BY_ID = new Map(MOCK_TITLES.map((title) => [title.id, title]));

export function getMockTitle(id: string): Title | undefined {
  return BY_ID.get(id);
}

function pick(slugs: string[]): Title[] {
  return slugs.flatMap((slug) => {
    const title = BY_ID.get(`mock-${slug}`);
    return title ? [title] : [];
  });
}

export function createMockCatalog(): { hero: Title; rows: CatalogRow[] } {
  const hero = pick(TRENDING_SLUGS)[0] ?? MOCK_TITLES[0];
  if (!hero) throw new Error('Demo catalog is empty');
  const rows: CatalogRow[] = [
    { id: 'trending', title: STRINGS.en.trending, titleAr: STRINGS.ar.trending, titles: pick(TRENDING_SLUGS) },
    {
      id: 'top',
      title: STRINGS.en.topRated,
      titleAr: STRINGS.ar.topRated,
      titles: [...MOCK_TITLES].sort((a, b) => b.rating - a.rating).slice(0, 16),
    },
    { id: 'open', title: STRINGS.en.openCinema, titleAr: STRINGS.ar.openCinema, titles: pick(OPEN_SLUGS) },
  ];
  for (const genreId of GENRE_ORDER) {
    const titles = MOCK_TITLES.filter((title) => title.genreIds.includes(genreId));
    if (titles.length < 4) continue;
    rows.push({
      id: `genre-${genreId}`,
      title: genreLabel(genreId, 'en'),
      titleAr: genreLabel(genreId, 'ar'),
      titles,
    });
  }
  return { hero, rows };
}

export function searchMock(query: string): Title[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return [];
  return MOCK_TITLES.filter((title) => {
    const genres = title.genreIds.map((id) => `${genreLabel(id, 'en')} ${genreLabel(id, 'ar')}`).join(' ');
    const haystack = [title.title, title.titleAr, title.overview, title.overviewAr, genres].join(' ').toLowerCase();
    return haystack.includes(needle);
  }).slice(0, 24);
}

