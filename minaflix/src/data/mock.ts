function fictionalCast(seed: number): CastMember[] {
  return [0, 1, 2].map((offset) => {
    const person = NAMES[(seed + offset * 5) % NAMES.length] ?? NAMES[0];
    const role = ROLES[(seed + offset * 3) % ROLES.length] ?? ROLES[0];
    return {
      id: seed * 10 + offset,
      name: person?.en ?? 'Cast',
      nameAr: person?.ar ?? 'طاقم',
      character: role?.en ?? 'Cast',
      characterAr: role?.ar ?? 'طاقم',
      profileUrl: null,
    };
  });
}

function credited(id: number, name: string, nameAr: string, character: string, characterAr: string): CastMember {
  return { id, name, nameAr, character, characterAr, profileUrl: null };
}

